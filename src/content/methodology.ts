import type { IndicatorId } from '../types';

/** Формула: expression — моноширинная строка, explain — человеческое пояснение. */
export interface MethodFormula {
  id: string;
  /** «Выручка с гектара» */
  label: string;
  /** «выручка на га = урожайность (т/га) × цена (₽/т)» */
  expression: string;
  explain: string;
}

export interface MethodList {
  /** Необязательный подзаголовок списка */
  title?: string;
  /** true — нумерованный (шаги), false — маркированный */
  ordered: boolean;
  items: string[];
}

export interface MethodNote {
  /** info — пояснение, warning — важное предупреждение (иконка + подпись, не только цвет) */
  kind: 'info' | 'warning';
  title: string;
  text: string;
}

/** Секция методики. Порядок вывода: question → lead → paragraphs → formulas → lists → notes. */
export interface MethodSection {
  id: string;
  /** Заголовок-вопрос */
  question: string;
  /** Короткий ответ в одну-две фразы, выводится крупно */
  lead: string;
  paragraphs?: string[];
  formulas?: MethodFormula[];
  lists?: MethodList[];
  notes?: MethodNote[];
}

/** Строка таблицы показателей (раздел 6 CLAUDE.md). Ключ совпадает с IndicatorId. */
export interface IndicatorRow {
  id: IndicatorId;
  name: string;
  unit: string;
  /** Человеческая периодичность */
  frequency: string;
  source: string;
  /** Короткая подсказка «что это» */
  hint?: string;
  /** true — данные на сайте реальные, false — демо-ряд (бейдж «Демо-данные») */
  real: boolean;
}

export interface Methodology {
  title: string;
  lead: string;
  sections: MethodSection[];
  indicators: {
    title: string;
    lead: string;
    columns: { indicator: string; unit: string; frequency: string; source: string; status: string };
    statusReal: string;
    statusDemo: string;
    rows: IndicatorRow[];
  };
  replaceDemo: {
    title: string;
    lead: string;
    steps: Array<{ title: string; text: string; command?: string }>;
    note: string;
  };
}

